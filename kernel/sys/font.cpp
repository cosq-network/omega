void draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg) {
    if (!framebuffer_active()) {
        return;
    }

    const uint8_t* glyph = font::glyph_for(c);
    for (uint8_t row = 0; row < font::glyph_height(); ++row) {
        const uint8_t bits = glyph[row];
        for (uint8_t col = 0; col < font::glyph_width(); ++col) {
            const bool on = (bits & (1u << (7 - col))) != 0;
            put_pixel(x + col, y + row, on ? fg : bg);
        }
    }
}

void draw_string(uint32_t x, uint32_t y, const char* s, uint32_t fg, uint32_t bg) {
    if (s == nullptr) {
        return;
    }
    uint32_t cursor_x = x;
    const uint32_t advance = font::glyph_width();
    while (*s) {
        draw_char(cursor_x, y, *s, fg, bg);
        cursor_x += advance;
        ++s;
    }
}

