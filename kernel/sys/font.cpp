static const uint8_t* glyph_rows(char c) {
    static uint8_t expanded[16];
    static uint8_t last_rows[8];

    char lookup = c;
    if (lookup < 32 || lookup > 126) {
        lookup = '?';
    }

    const uint8_t* src = font8x8[static_cast<uint8_t>(lookup) - 32];
    for (int i = 0; i < 8; ++i) {
        last_rows[i] = src[i];
        expanded[i * 2]     = src[i];
        expanded[i * 2 + 1] = src[i];
    }
    (void)last_rows;
    return expanded;
}

uint8_t glyph_width() { return GLYPH_W; }
uint8_t glyph_height() { return GLYPH_H; }
const uint8_t* glyph_for(char c) { return glyph_rows(c); }

